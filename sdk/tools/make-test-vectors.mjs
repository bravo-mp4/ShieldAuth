// Regenerates sdk/test-vectors.json: a throwaway key pair and signed
// answers that every SDK's tests check against, so they all agree with the
// server about exactly what is signed.
//
//   node sdk/tools/make-test-vectors.mjs
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const { privateKey, publicKey } = crypto.generateKeyPairSync("ec", { namedCurve: "prime256v1" });

const message = (type, fields) => ["shieldauth-v1", type, ...fields.map(String)].join("\n");
const sign = (text) =>
  crypto.sign("sha256", Buffer.from(text), { key: privateKey, dsaEncoding: "ieee-p1363" }).toString("base64");

const validate = {
  app_id: "0123456789abcdef0123456789abcdef",
  license_key: "A1B2C3D4E5F60718293A4B5C6D7E8F90",
  hwid: "9f2c1e0b7a6d5c4b3a2918f7e6d5c4b3a2918f7e6d5c4b3a2918f7e6d5c4b3a2",
  nonce: "c2hpZWxkYXV0aC10ZXN0LW5vbmNl",
  valid: true,
  session_id: "5e55" + "a".repeat(60),
  expires_at: 1893456000,
  signed_at: 1767225600,
};
const validateText = message("validate", [
  validate.app_id,
  validate.license_key,
  validate.hwid,
  validate.nonce,
  validate.valid ? 1 : 0,
  validate.session_id,
  validate.expires_at,
  validate.signed_at,
]);

const heartbeat = {
  session_id: validate.session_id,
  nonce: "aGVhcnRiZWF0LW5vbmNlLTAx",
  valid: false,
  signed_at: 1767225900,
};
const heartbeatText = message("heartbeat", [heartbeat.session_id, heartbeat.nonce, heartbeat.valid ? 1 : 0, heartbeat.signed_at]);

const vectors = {
  comment: "Generated by sdk/tools/make-test-vectors.mjs. Test-only key; never use it for real.",
  public_key_pem: publicKey.export({ type: "spki", format: "pem" }).toString(),
  validate: { ...validate, message: validateText, signature: sign(validateText) },
  heartbeat: { ...heartbeat, message: heartbeatText, signature: sign(heartbeatText) },
};

fs.writeFileSync(path.join(here, "..", "test-vectors.json"), JSON.stringify(vectors, null, 2) + "\n");
console.log("wrote sdk/test-vectors.json");
